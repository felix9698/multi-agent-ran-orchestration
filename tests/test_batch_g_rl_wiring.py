class TrainedRLPolicyTest(unittest.TestCase):
    def test_training_is_reproducible(self):
        a = train_tabular_policy(RLTrainingConfig())
        b = train_tabular_policy(RLTrainingConfig())
        self.assertEqual(a.digest, b.digest)
        self.assertEqual(a.policy, b.policy)

    def test_digest_is_canonical_sha256(self):
        a = train_tabular_policy(RLTrainingConfig())
        self.assertTrue(a.digest.startswith("rlpolicy-sha256-"))
        # 64 hex chars after the prefix
        self.assertEqual(len(a.digest.split("sha256-")[1]), 64)

    def test_provenance_records_training(self):
        a = train_tabular_policy(RLTrainingConfig())
        for k in ("algorithm", "learned", "config", "env_digest", "n_episodes"):
            self.assertIn(k, a.provenance)
        self.assertTrue(a.provenance["learned"])
        self.assertIn("q_learning", a.provenance["algorithm"])

    def test_policy_is_learned_not_handcrafted(self):
        # the learned policy responds monotonically to deficit and caps near the
        # I1 bound (3 dB) - an emergent optimum, not a fixed step table.
        cfg = RLTrainingConfig()
        a = train_tabular_policy(cfg)
        small = a.action_for_deficit(0.3, cfg)
        big = a.action_for_deficit(6.0, cfg)
        self.assertLessEqual(small, big)
        self.assertLessEqual(big, cfg.i1_power_bound_db + 1e-9)

    def test_artifact_roundtrip_and_reproduction(self):
        cfg = RLTrainingConfig()
        a = train_tabular_policy(cfg)
        with tempfile.TemporaryDirectory() as tmp:
            p = os.path.join(tmp, "policy.json")
            save_artifact(a, p)
            b = load_artifact(p, cfg=cfg, verify_reproduction=True)
            self.assertEqual(a.digest, b.digest)

    def test_corrupted_policy_is_rejected(self):
        cfg = RLTrainingConfig()
        a = train_tabular_policy(cfg)
        with tempfile.TemporaryDirectory() as tmp:
            p = os.path.join(tmp, "policy.json")
            save_artifact(a, p)
            with open(p) as fh:
                d = json.load(fh)
            d["policy"]["0"] = 99.0            # tamper a policy entry
            with open(p, "w") as fh:
                json.dump(d, fh)
            with self.assertRaises(RLArtifactError):
                load_artifact(p, cfg=cfg)

    def test_tampered_digest_is_rejected(self):
        cfg = RLTrainingConfig()
        a = train_tabular_policy(cfg)
        with tempfile.TemporaryDirectory() as tmp:
            p = os.path.join(tmp, "policy.json")
            save_artifact(a, p)
            with open(p) as fh:
                d = json.load(fh)
            d["digest"] = "rlpolicy-sha256-" + "0" * 64
            with open(p, "w") as fh:
                json.dump(d, fh)
            with self.assertRaises(RLArtifactError):
                load_artifact(p, cfg=cfg)

    def test_config_mismatch_is_rejected(self):
        cfg = RLTrainingConfig()
        a = train_tabular_policy(cfg)
        with tempfile.TemporaryDirectory() as tmp:
            p = os.path.join(tmp, "policy.json")
            save_artifact(a, p)
            other = RLTrainingConfig(n_episodes=cfg.n_episodes + 1)
            with self.assertRaises(RLArtifactError):
                load_artifact(p, cfg=other)

    def test_checked_in_artifact_validates(self):
        # the packaged artifact (generated by python -m decision.rl_controller)
        path = _default_artifact_path()
        if os.path.isfile(path):
            tp = load_artifact(path, cfg=RLTrainingConfig(),
                               verify_reproduction=True)
            self.assertTrue(tp.provenance["learned"])


